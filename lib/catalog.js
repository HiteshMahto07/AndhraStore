/**
 * lib/catalog.js — client-safe helpers shared by the Meta catalog feed and analytics.
 *
 * Meta matches Pixel events to catalog items ONLY when the Pixel's
 * `content_ids` equal the feed's `id`. The Pixel's content_ids come from the
 * GA4 ecommerce `item_id` (GTM variable "CJS - Meta Content IDs"), so both
 * lib/analytics.js and lib/metaCatalog.js must derive ids from catalogId().
 *
 * Id scheme (stable — changing it orphans Meta's catalog history and audiences):
 *   glass / default  → product.type             e.g. "Mango"
 *   pouch variant    → `${product.type}-pouch`  e.g. "Mango-pouch"
 * 500g / 1kg are multiples of the same 250g pack, so they share the pack's id.
 *
 * Keep this file free of data imports — it ships in every page's bundle.
 */

export function catalogId(type, packaging = 'glass') {
  return packaging === 'pouch' ? `${type}-pouch` : type;
}

// Meta catalogs accept JPEG/PNG only; the site serves WebP. Every product
// image has a JPEG twin generated by scripts/generate-catalog-images.js.
// Keep this mapping identical to catalogImagePath() in that script.
export function catalogImagePath(src) {
  return `/catalog${src.replace(/\.(webp|jpe?g|png)$/i, '.jpg')}`;
}
